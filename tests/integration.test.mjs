import test from "node:test";
import assert from "node:assert/strict";
import {
  mkdtemp,
  mkdir,
  writeFile,
  readFile,
  readdir,
  symlink,
  rm,
  realpath,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash } from "node:crypto";
import { listBatchRuns } from "../server/store.mjs";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const exec = promisify(execFile);
async function sources(directory) {
  const output = {};
  async function walk(path, prefix = "") {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      if (entry.name === "node_modules") continue;
      if (entry.isDirectory())
        await walk(join(path, entry.name), `${prefix}${entry.name}/`);
      else
        output[`${prefix}${entry.name}`] = createHash("sha256")
          .update(await readFile(join(path, entry.name)))
          .digest("hex");
    }
  }
  await walk(directory);
  return output;
}
for (const format of ["cjs", "mjs", "ts", "esm-ts"]) {
  test(
    `external integration preserves ${format} sources, async hooks, tasks and custom reporter`,
    { timeout: 90_000 },
    async () => {
      const scratch = await mkdtemp(join(tmpdir(), "cypress-pulse-"));
      try {
        const project = join(scratch, "project");
        await mkdir(join(project, "cypress", "e2e"), { recursive: true });
        await symlink(
          join(root, "node_modules"),
          join(project, "node_modules"),
          "dir",
        );
        await writeFile(
          join(project, "package.json"),
          JSON.stringify({
            private: true,
            type:
              format === "mjs" || format === "esm-ts" ? "module" : "commonjs",
          }),
        );
        const extension = format === "esm-ts" ? "ts" : format;
        const typed = format === "ts" || format === "esm-ts";
        const config = join(project, `cypress.config.${extension}`);
        if (typed)
          await writeFile(
            join(project, "settings.ts"),
            "export const viewport: number = 333;\n",
          );
        const body = `const options = {video: false, reporter: './reporter.cjs', e2e: {supportFile: false, async setupNodeEvents(on, config) {if (fs.realpathSync(config.configFile) !== fs.realpathSync(${JSON.stringify(config)})) throw Error('Original config filename changed'); on('task', {probe: () => 'preserved'}); on('after:spec', () => fs.appendFileSync(process.env.HOOK_FILE, 'called\\n')); await Promise.resolve(); return {...config, viewportWidth: ${typed ? "width" : "333"}};}}};`;
        const source =
          format === "cjs"
            ? `const fs = require('node:fs'); ${body} module.exports = options;`
            : typed
              ? `import fs from 'node:fs'; import {defineConfig} from 'cypress'; import {viewport} from './settings.ts'; const width: number = viewport; ${body} export default defineConfig(options);`
              : `import fs from 'node:fs'; ${body} export default options;`;
        await writeFile(config, source);
        await writeFile(
          join(project, "reporter.cjs"),
          `const fs=require('node:fs'); module.exports=class {constructor(runner) {runner.on('pass',()=>fs.appendFileSync(process.env.REPORTER_FILE,'pass\\n'));}};`,
        );
        await writeFile(
          join(project, "cypress", "e2e", "sample.cy.js"),
          `// Generated by Cypress Author on 2026-10-14 for the isolated integration fixture.\ndescribe('Pulse compatibility', () => {it('preserves returned config and tasks', () => {expect(Cypress.config('viewportWidth')).to.equal(333); cy.task('probe').should('equal', 'preserved');}); it('passes on retry', {retries: 1}, () => expect(Cypress.currentRetry).to.equal(1)); it.skip('pending', () => {}); it('reports failure', () => expect('actual').to.equal('expected'));});`,
        );
        const before = await sources(project);
        const state = join(scratch, "state");
        const hookFile = join(scratch, "hooks.txt");
        const reporterFile = join(scratch, "reporter.txt");
        let exitCode = 0;
        try {
          await exec(
            process.execPath,
            [
              (process.env.CYPRESS_PULSE_TEST_HELPER || join(root, "server", "cli.mjs")),
              "run",
              "--project",
              project,
              "--state-dir",
              state,
              ...(process.env.CYPRESS_PULSE_TEST_CLI
                ? ["--cypress-cli", process.env.CYPRESS_PULSE_TEST_CLI]
                : []),
              "--",
              "--browser",
              "electron",
              "--config",
              `screenshotsFolder=${join(scratch, "images")}`,
            ],
            {
              env: {
                ...process.env,
                HOOK_FILE: hookFile,
                REPORTER_FILE: reporterFile,
              },
              maxBuffer: 4 * 1024 * 1024,
              timeout: 80_000,
            },
          );
        } catch (error) {
          exitCode = error.code;
          if (exitCode !== 1) throw error;
          // Configuration failures also exit 1, so verify actual run contents below.
          if (!error.stdout?.includes("Run Finished"))
            throw new Error(error.stdout + "\n" + error.stderr);
        }
        assert.equal(exitCode, 1);
        const runs = await listBatchRuns(state, await realpath(project));
        assert.equal(runs.length, 1);
        const run = runs[0];
        assert.equal(run.status, "failed");
        assert.deepEqual([run.passed, run.failed, run.pending], [2, 1, 1]);
        assert.equal(run.retries, 1);
        assert.equal(run.tests.length, 4);
        assert.match(
          run.tests.find((test) => test.status === "failed").error.message,
          /expected/,
        );
        assert.ok(
          run.tests.find((test) => test.status === "failed").duration > 0,
        );
        assert.ok(run.artifacts.some((item) => item.kind === "screenshot"));
        assert.equal((await readFile(hookFile, "utf8")).trim(), "called");
        assert.equal(
          (await readFile(reporterFile, "utf8")).trim().split("\n").length,
          2,
        );
        assert.deepEqual(await sources(project), before);
      } finally {
        await rm(scratch, { recursive: true, force: true });
      }
    },
  );
}
